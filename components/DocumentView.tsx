import type { GeneratedDocument } from "@/lib/documents";

// Presentational, print-friendly render of a prepared document. Server component (no client JS); the
// only interactive bit, Print/Save-as-PDF, is a separate island the page drops in.
export function DocumentView({ doc }: { doc: GeneratedDocument }) {
  return (
    <article className="packet-page">
      <header className="mb-6 border-b pb-4" style={{ borderColor: "var(--color-line)" }}>
        <p className="cfr">{doc.cfrCite}</p>
        <h1 className="mt-1 font-serif text-3xl font-semibold leading-tight">{doc.title}</h1>
        <p className="mt-2 text-sm" style={{ color: "var(--color-muted)" }}>
          {doc.purpose}
        </p>
        <p className="mt-3 text-xs font-medium" style={{ color: "var(--color-muted)" }}>
          {doc.prefilledCount} field{doc.prefilledCount === 1 ? "" : "s"} pre-filled · {doc.blankCount} for
          you to complete
        </p>
      </header>

      <div className="space-y-7">
        {doc.sections.map((s) => (
          <section key={s.heading}>
            <h2 className="font-serif text-xl font-semibold">{s.heading}</h2>
            {s.note && (
              <p className="mt-1 text-sm" style={{ color: "var(--color-muted)" }}>
                {s.note}
              </p>
            )}
            <dl className="mt-3 divide-y" style={{ borderColor: "var(--color-line)" }}>
              {s.fields.map((f) => (
                <div key={f.label} className="grid grid-cols-1 gap-1 py-2.5 sm:grid-cols-3 sm:gap-4">
                  <dt className="text-sm font-medium">{f.label}</dt>
                  <dd className="sm:col-span-2">
                    {f.status === "prefilled" ? (
                      <span className="inline-flex items-center gap-2 text-sm">
                        <span
                          className="badge"
                          style={{ color: "var(--color-good)", borderColor: "var(--color-good)" }}
                        >
                          Pre-filled
                        </span>
                        <span className="font-medium">{f.value}</span>
                      </span>
                    ) : (
                      <span className="block">
                        <span
                          className="block h-7 w-full rounded border border-dashed"
                          style={{ borderColor: "var(--color-line-strong)" }}
                          aria-hidden="true"
                        />
                        {f.hint && (
                          <span className="mt-1 block text-xs" style={{ color: "var(--color-muted)" }}>
                            {f.hint}
                          </span>
                        )}
                      </span>
                    )}
                  </dd>
                </div>
              ))}
            </dl>
          </section>
        ))}
      </div>

      <footer className="mt-8 border-t pt-4 text-xs" style={{ borderColor: "var(--color-line)", color: "var(--color-muted)" }}>
        Decision-support, not legal advice. Verify current form versions and requirements against FMCSA
        before filing or signing. Generated by DOT Navigator from your saved profile.
      </footer>
    </article>
  );
}
